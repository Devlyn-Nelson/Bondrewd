//! `#[bondrewd(dump)]`: writes the generated code to
//! `<target dir>/bondrewd_dump/<crate name>/<Type>.<derive>.rs` for inspection.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use proc_macro2::{Delimiter, Spacing, TokenStream, TokenTree};

/// Writes `tokens` to the dump file and returns its path.
pub fn write(type_name: &str, derive: &str, tokens: &TokenStream) -> Result<PathBuf, String> {
    let crate_name = env::var("CARGO_CRATE_NAME").unwrap_or_else(|_| "unknown_crate".into());
    let dir = target_dir().join("bondrewd_dump").join(crate_name);
    fs::create_dir_all(&dir).map_err(|e| format!("bondrewd dump: can't create {}: {e}", dir.display()))?;
    let path = dir.join(format!("{type_name}.{derive}.rs"));

    let mut f = Formatter::default();
    f.tokens(tokens.clone());
    let text = format!(
        "// Generated by bondrewd: `#[derive({})]` on `{type_name}`.\n\
         // Written because of `#[bondrewd(dump)]`; changes here have no effect.\n\n{}\n",
        if derive == "bitfields" { "Bitfields" } else { "BitfieldsSlice" },
        f.out.trim_end()
    );
    fs::write(&path, text).map_err(|e| format!("bondrewd dump: can't write {}: {e}", path.display()))?;

    // Best effort: tidy it up with rustfmt when it's installed. The built-in formatting
    // above is already readable, so failures are ignored.
    let _ = Command::new(env::var_os("RUSTFMT").unwrap_or_else(|| "rustfmt".into()))
        .args(["--edition", "2024"])
        .arg(&path)
        .output();
    Ok(path)
}

/// `CARGO_TARGET_DIR`, or `target/` in the workspace root of the crate being compiled.
fn target_dir() -> PathBuf {
    let root = workspace_root();
    match env::var_os("CARGO_TARGET_DIR").map(PathBuf::from) {
        Some(dir) if dir.is_absolute() => dir,
        Some(dir) => root.join(dir),
        None => root.join("target"),
    }
}

fn workspace_root() -> PathBuf {
    let manifest = env::var_os("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .or_else(|| env::current_dir().ok())
        .unwrap_or_default();
    manifest
        .ancestors()
        .filter(|dir| is_workspace(dir))
        .last()
        .map_or_else(|| manifest.clone(), Path::to_path_buf)
}

fn is_workspace(dir: &Path) -> bool {
    fs::read_to_string(dir.join("Cargo.toml")).is_ok_and(|s| s.lines().any(|l| l.trim() == "[workspace]"))
}

/// Minimal token pretty printer, used as-is when rustfmt isn't available: a line per
/// statement or item, an indent per brace block and Rust-like spacing.
#[derive(Default)]
struct Formatter {
    out: String,
    indent: usize,
    /// Enclosing delimiters; `;` and `,` only break lines directly inside braces.
    groups: Vec<Delimiter>,
    prev: Prev,
    /// Open `<` generic brackets, so the matching `>` is glued.
    angles: usize,
    /// A `}` was just written; the next token decides whether a new line follows.
    after_brace: bool,
    /// Break the line before the next token (after `;`, `,` or an attribute).
    pending_newline: bool,
}

#[derive(Default, Clone, PartialEq)]
enum Prev {
    #[default]
    Start,
    Ident(String),
    Literal,
    Punct(char, Spacing),
    Open,
    Close,
}

const KEYWORDS: &[&str] = &["impl", "for", "as", "in", "dyn", "return", "let", "mut", "ref", "where", "fn", "if", "match"];

impl Formatter {
    fn in_block(&self) -> bool {
        matches!(self.groups.last(), None | Some(Delimiter::Brace))
    }

    fn newline(&mut self) {
        if !self.out.is_empty() && !self.out.ends_with('\n') {
            self.out.push('\n');
        }
    }

    /// Writes `s`, separated from the previous token by a space unless `glue`.
    fn push(&mut self, s: &str, glue: bool) {
        let continues = s.starts_with(['=', ',', ';', '.', '?', ')', ']']);
        if self.after_brace && !continues && self.in_block() {
            self.pending_newline = true;
        }
        self.after_brace = false;
        if self.pending_newline {
            self.newline();
            self.pending_newline = false;
        }
        if self.out.is_empty() || self.out.ends_with('\n') {
            self.out.push_str(&"    ".repeat(self.indent));
        } else if !glue {
            self.out.push(' ');
        }
        self.out.push_str(s);
    }

    fn prev_is_value(&self) -> bool {
        matches!(&self.prev, Prev::Literal | Prev::Close) || matches!(&self.prev, Prev::Ident(i) if !KEYWORDS.contains(&i.as_str()))
    }

    fn tokens(&mut self, tokens: TokenStream) {
        for tt in tokens {
            match tt {
                TokenTree::Group(g) => self.group(&g),
                TokenTree::Punct(p) => self.punct(p.as_char(), p.spacing()),
                TokenTree::Ident(i) => {
                    let glue = self.glue_after_punct();
                    self.push(&i.to_string(), glue);
                    self.prev = Prev::Ident(i.to_string());
                }
                TokenTree::Literal(l) => {
                    let glue = self.glue_after_punct();
                    self.push(&l.to_string(), glue);
                    self.prev = Prev::Literal;
                }
            }
        }
    }

    /// Whether the next token sticks to the previous one.
    fn glue_after_punct(&self) -> bool {
        match self.prev {
            Prev::Punct(':', _) => self.out.ends_with("::"),
            Prev::Punct('<', _) => self.angles > 0 && self.out.ends_with('<'),
            // Method calls, attributes, unary operators (recorded as joint) and the
            // second half of multi-character operators.
            Prev::Punct('.' | '#', _) | Prev::Punct(_, Spacing::Joint) | Prev::Open => true,
            _ => false,
        }
    }

    fn punct(&mut self, c: char, spacing: Spacing) {
        let joined = matches!(self.prev, Prev::Punct(_, Spacing::Joint)) && self.out.ends_with(|p: char| p.is_ascii_punctuation() && p != ')' && p != ']');
        let glue = match c {
            ',' | ';' | '.' | '?' => true,
            ':' if self.out.ends_with(':') => true,
            ':' if spacing == Spacing::Joint => {
                self.prev_is_value()
                    || matches!(self.prev, Prev::Open)
                    || (self.out.ends_with('>') && !self.out.ends_with("->"))
            }
            ':' => true,
            '<' => {
                let generic = spacing == Spacing::Alone
                    && (matches!(&self.prev, Prev::Ident(i) if !KEYWORDS.contains(&i.as_str()))
                        || self.out.ends_with("::"));
                if generic {
                    self.angles += 1;
                }
                generic || joined
            }
            '>' if self.angles > 0 && !joined => {
                self.angles -= 1;
                true
            }
            _ => joined || matches!(self.prev, Prev::Open | Prev::Punct('.' | '#', _)),
        };
        // A unary `&`, `-`, `!` or `*` sticks to the following token.
        let unary = matches!(c, '&' | '-' | '!' | '*') && !self.prev_is_value() && !joined;
        self.push(&c.to_string(), glue);
        self.prev = Prev::Punct(c, if unary { Spacing::Joint } else { spacing });
        if (c == ';' || (c == ',' && self.angles == 0)) && self.in_block() {
            self.pending_newline = true;
        }
    }

    fn group(&mut self, g: &proc_macro2::Group) {
        let delim = g.delimiter();
        match delim {
            Delimiter::None => self.tokens(g.stream()),
            Delimiter::Brace if g.stream().is_empty() => {
                let glue = matches!(self.prev, Prev::Open);
                self.push("{}", glue);
                self.after_brace = true;
                self.prev = Prev::Close;
            }
            Delimiter::Brace => {
                let glue = matches!(self.prev, Prev::Open);
                self.push("{", glue);
                self.indent += 1;
                self.groups.push(delim);
                self.prev = Prev::Start;
                self.pending_newline = true;
                self.tokens(g.stream());
                self.groups.pop();
                self.indent -= 1;
                self.pending_newline = false;
                self.newline();
                self.push("}", false);
                self.after_brace = true;
                self.prev = Prev::Close;
            }
            Delimiter::Parenthesis | Delimiter::Bracket => {
                let (open, close) = if delim == Delimiter::Bracket { ("[", "]") } else { ("(", ")") };
                let attribute = delim == Delimiter::Bracket && self.out.ends_with('#');
                let glue = attribute
                    || self.prev_is_value()
                    || matches!(self.prev, Prev::Open | Prev::Punct('!' | '&', _))
                    || (matches!(self.prev, Prev::Punct('>', _)) && self.angles == 0 && self.out.ends_with('>') && !self.out.ends_with("->"));
                let glue = glue && !matches!(&self.prev, Prev::Ident(i) if KEYWORDS.contains(&i.as_str()));
                self.push(open, glue);
                self.groups.push(delim);
                self.prev = Prev::Open;
                self.tokens(g.stream());
                self.groups.pop();
                self.push(close, true);
                self.prev = Prev::Close;
                if attribute && self.in_block() {
                    self.pending_newline = true;
                }
            }
        }
    }
}
